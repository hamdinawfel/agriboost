const mongoose = require("mongoose");
const Schema = mongoose.Schema;

const reclamationSchema = new Schema(
  {
    cin: {
      type: String,
      required: true,
    },
    firstName: {
      type: String,
      required: true,
    },
    lastName: {
      type: String,
      required: true,
    },
    phone: {
      type: String,
      required: true,
    },
    message: {
      type: String,
      required: true,
    },
  },
  {
    timestamps: true,
  }
);

module.exports = mongoose.model("reclamations", reclamationSchema);
